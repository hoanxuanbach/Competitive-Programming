const int mod = 1e9+7;
int power(int a,int n){
    int res=1;
    while(n){
        if(n&1) res=res*a%mod;
        a=a*a%mod;n>>=1;
    }
    return res;
}
 
const int maxn = 2e5+5;
const int inf = 1e18;

mt19937_64 rng(chrono::steady_clock::now().time_since_epoch().count());
int rand_int(int l,int r){
    return l+abs((int)rng())%(r-l+1);
}

void solve(){
    int N;cin >> N;
    int res=0;
    for(int k=1;k<=N;k++){
        int x=(1-k*k%mod+mod)%mod;
        int d=(power(x,N+1)-x+mod)%mod;
        res=(res+d*power(x-1,mod-2))%mod;
    }
    cout << res << '\n';
}
 
